Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await Hive.initFlutter();
  final sleepBox = await Hive.openBox<String>(DuoNapHiveSleepRepository.boxName);
  final settingsBox = await Hive.openBox<String>(DuoNapHiveSettingsRepository.boxName);
  runApp(
    ProviderScope(
      overrides: _overrides(sleepBox, settingsBox),
      child: const DuoNapApp(),
    ),
  );
}

/// The phone's own stores, wrapped so every change also reaches the family.
List<Override> _overrides(Box<String> sleepBox, Box<String> settingsBox) {
  final firestore = FirebaseFirestore.instance;
  final local = DuoNapLocalStores(
    sleep: DuoNapHiveSleepRepository(sleepBox),
    settings: DuoNapHiveSettingsRepository(settingsBox),
    shift: DuoNapHiveShiftRepository(settingsBox),
  );
  final cloud = DuoNapFirestoreFamily(firestore, FirebaseAuth.instance);
  final sessions = DuoNapSessionMirror(local: local.sleep, cloud: DuoNapFirestoreSessions(firestore));
  final family = DuoNapFamilyMirror(cloud: cloud, settings: local.settings, shift: local.shift);
  final familyRepository = DuoNapCloudFamilyRepository(
    cloud: cloud,
    link: DuoNapFamilyLinkStore(settingsBox),
    sessions: sessions,
    family: family,
    local: local,
  );
  return [
    duoNapSleepRepositoryProvider.overrideWithValue(DuoNapSyncedSleepRepository(local.sleep, sessions)),
    duoNapSettingsRepositoryProvider.overrideWithValue(DuoNapSyncedSettingsRepository(local.settings, family)),
    duoNapShiftRepositoryProvider.overrideWithValue(DuoNapSyncedShiftRepository(local.shift, family)),
    duoNapFamilyRepositoryProvider.overrideWithValue(familyRepository),
  ];
}
